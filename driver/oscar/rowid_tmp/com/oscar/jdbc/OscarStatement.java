    private String parseAnonymous(String o_sql) {
        StringBuffer cmd = new StringBuffer(o_sql.trim());
        if (cmd.toString().length() >= 7 && cmd.toString().substring(0, 7).equalsIgnoreCase("declare")) {
            if (cmd.toString().toLowerCase().contains("begin")) {
                cmd.insert(0, "DO ");
                this.isAnonymous = true;
            }
        } else if (cmd.toString().length() >= 5 && cmd.toString().substring(0, 5).equalsIgnoreCase("begin")) {
            if (cmd.toString().toLowerCase().contains("end")) {
                cmd.insert(0, "DO ");
                this.isAnonymous = true;
            }
        } else if (cmd.toString().length() >= 2 && cmd.toString().substring(0, 2).equalsIgnoreCase("<<")) {
            cmd.insert(0, "DO ");
            this.isAnonymous = true;
        }
        return cmd.toString();
    }

